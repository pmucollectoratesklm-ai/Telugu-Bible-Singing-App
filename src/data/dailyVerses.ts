/**
 * Deterministically get the Verse of the Day based on the current calendar date
 */
export function getTodayVerse(offsetDays: number = 0): DailyVerse {
  const now = new Date();
  if (offsetDays !== 0) {
    now.setDate(now.getDate() + offsetDays);
  }

  // Calculate day of the year
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  const index = (dayOfYear + now.getFullYear()) % DAILY_VERSES.length;
  return DAILY_VERSES[index];
}

/**
 * Format Date into Telugu & English
 */
export function getFormattedTeluguDate(date: Date = new Date()): {
  teluguDate: string;
  englishDate: string;
} {
  const teluguMonths = [
    'జనవరి',
    'ఫిబ్రవరి',
    'మార్చి',
    'ఏప్రిల్',
    'మే',
    'జూన్',
    'జూలై',
    'ఆగస్టు',
    'సెప్టెంబర్',
    'అక్టోబర్',
    'నవంబర్',
    'డిసెంబర్',
  ];

  const teluguDays = [
    'ఆదివారం',
    'సోమవారం',
    'మంగళవారం',
    'బుధవారం',
    'గురువారం',
    'శుక్రవారం',
    'శనివారం',
  ];

  const dayOfMonth = date.getDate();
  const monthName = teluguMonths[date.getMonth()];
  const year = date.getFullYear();
  const dayOfWeek = teluguDays[date.getDay()];

  const options: Intl.DateTimeFormatOptions = {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  };
  const englishDate = date.toLocaleDateString('en-US', options);

  return {
    teluguDate: `${dayOfMonth} ${monthName} ${year} (${dayOfWeek})`,
    englishDate,
  };
}
